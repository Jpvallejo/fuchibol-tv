const mtRed = ["cdnlb", "cdn02", "cdn03"];

function getGigaredHost(): string {
  return mtRed[Math.floor(Math.random() * mtRed.length)];
}

function buildGigaredManifest(path: string): string {
  return `https://${getGigaredHost()}.gigared.com.ar${path}`;
}

function buildProxyHlsUrl(rawUrl: string): string {
  const encodedUrl = encodeURIComponent(rawUrl)
  return `https://fuchibol.vallejo.ar/api/proxy-hls?url=${encodedUrl}`
}

const CVATTV_RESOLVE_BACKEND_URL = 'https://fuchibol.vallejo.ar/api/get-cvattv-proxy'

async function fetchCvattvStreamUrl(path: string): Promise<string> {
  return path;
  const endpoint = `${CVATTV_RESOLVE_BACKEND_URL}?path=${encodeURIComponent(path)}`
  const response = await fetch(endpoint, {
    method: 'GET',
    headers: {
      accept: 'application/json',
    },
  })

  if (!response.ok) {
    throw new Error(`Failed to resolve CVATTV stream: ${response.status} ${response.statusText}`)
  }

  const payload = await response.json() as { redirectUrl?: string }
  if (!payload.redirectUrl) {
    throw new Error('CVATTV resolver did not return redirectUrl')
  }

  // return payload.redirectUrl;
}

